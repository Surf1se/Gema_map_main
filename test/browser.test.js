test('Yandex tiles use Web Mercator and display the required logo', { timeout: 30_000 }, async t => {
  const instance = createApp({ database: ':memory:', secureCookies: false, yandexTilesKey: 'test-tiles-key' });
  const server = instance.app.listen(0, '127.0.0.1'); await once(server, 'listening');
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || (existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : undefined), args: ['--no-sandbox'] });
  t.after(async () => { await browser.close(); instance.close(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); });
  const page = await browser.newPage();
  const tileRequests = [];
  const logo = fileURLToPath(new URL('../public/yandex-logo.png', import.meta.url));
  await page.route('https://tiles.api-maps.yandex.ru/**', route => {
    tileRequests.push(new URL(route.request().url()));
    return route.fulfill({ path: logo, contentType: 'image/png' });
  });
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  await page.waitForFunction(() => document.querySelector('#yandex-logo')?.offsetParent !== null);
  await page.waitForFunction(() => [...document.querySelectorAll('.leaflet-tile')].some(tile => tile.complete && tile.naturalWidth));
  assert.ok(tileRequests.length > 0);
  assert.equal(tileRequests[0].searchParams.get('apikey'), 'test-tiles-key');
  assert.equal(tileRequests[0].searchParams.get('projection'), 'web_mercator');
  assert.equal(tileRequests[0].searchParams.get('lang'), 'ru_RU');
  assert.equal(await page.locator('#yandex-logo').getAttribute('href'), 'https://yandex.ru/maps/');
});

test('new alerts show dismissible toasts and change from red or blue to yellow after 30 minutes', { timeout: 30_000 }, async t => {
  const polygon = { type: 'Polygon', coordinates: [[[37.1, 55.3], [38.5, 55.3], [38.5, 56], [37.1, 56], [37.1, 55.3]]] };
  const instance = createApp({ database: ':memory:', secureCookies: false, boundaryLookup: async () => polygon });
  instance.applyPost({ id: 301, date: Date.now(), text: 'Московская область\nОпасность по БПЛА' });
  const server = instance.app.listen(0, '127.0.0.1'); await once(server, 'listening');
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || (existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : undefined), args: ['--no-sandbox'] });
  t.after(async () => { await browser.close(); instance.close(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  await page.clock.install();
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  await page.locator('#name').fill('Карта'); await page.locator('#email').fill('map@example.com'); await page.locator('#password').fill('correct horse battery');
  await page.locator('#auth-submit').click();
  await page.locator('#auth-dialog').waitFor({ state: 'hidden' });
  const regionPath = page.locator('.leaflet-alert-region-pane path').first();
  await regionPath.waitFor();
  assert.equal(await regionPath.getAttribute('fill'), '#df3b3b');
  assert.equal(await regionPath.getAttribute('stroke'), '#59636b');
  assert.equal(await page.locator('.alert-toast').count(), 0);

  instance.applyPost({ id: 302, date: Date.now(), text: 'МО Раменское\nМосковская область\nОпасность по БПЛА' });
  const cityPath = page.locator('.leaflet-alert-settlement-pane path').first();
  await cityPath.waitFor();
  assert.equal(await cityPath.getAttribute('fill'), '#168bd0');
  assert.equal(await cityPath.getAttribute('stroke'), '#59636b');
  await page.locator('.alert-toast').waitFor();
  assert.match(await page.locator('.alert-toast').textContent(), /Раменское/);
  const toastBox = await page.locator('.alert-toast').boundingBox();
  assert.ok(toastBox.x > 700 && toastBox.y < 170);
  await page.locator('.alert-toast button').click();
  assert.equal(await page.locator('.alert-toast').count(), 0);

  instance.applyPost({ id: 303, date: Date.now(), text: 'ГО Бронницы\nМосковская область\nРакетная опасность' });
  await page.locator('.alert-toast').waitFor();
  await page.clock.fastForward(120_001);
  assert.equal(await page.locator('.alert-toast').count(), 0);
  await page.clock.fastForward(28 * 60_000 + 5_000);
  await page.waitForFunction(() => [...document.querySelectorAll('.leaflet-alert-region-pane path, .leaflet-alert-settlement-pane path')].every(path => path.getAttribute('fill') === '#f4cc40'));
  await page.clock.setSystemTime(new Date());
  instance.applyPost({ id: 302, date: Date.now(), text: 'МО Раменское\nМосковская область\nОпасность по БПЛА' });
  await page.waitForFunction(() => [...document.querySelectorAll('.leaflet-alert-settlement-pane path')].some(path => path.getAttribute('fill') === '#168bd0'));
  assert.equal(await page.locator('.alert-toast').count(), 0);
});

test('map stays visible while online count follows users on desktop and mobile', { timeout: 60_000 }, async t => {
  const polygon = { type: 'Polygon', coordinates: [[[38.17, 55.48], [38.35, 55.48], [38.35, 55.61], [38.17, 55.61], [38.17, 55.48]]] };
  const instance = createApp({ database: ':memory:', secureCookies: false, boundaryLookup: async place => place.name === 'Раменское' ? polygon : null });
  const server = instance.app.listen(0, '127.0.0.1'); await once(server, 'listening');
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || (existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : undefined), args: ['--no-sandbox'] });
  t.after(async () => { await browser.close(); instance.close(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); });
  const url = `http://127.0.0.1:${server.address().port}`;
  const errors = [];
  const locationRequests = [];
  async function participant(name, email, mobile = false) {
    const context = await browser.newContext(mobile ? { viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true } : { viewport: { width: 1440, height: 1000 } });
    const page = await context.newPage();
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => { if (request.url().includes('/api/location')) locationRequests.push(request.url()); });
    await page.goto(url);
    await page.locator('#auth-dialog').waitFor({ state: 'visible' });
    await page.locator('#name').fill(name); await page.locator('#email').fill(email); await page.locator('#password').fill('correct horse battery');
    await page.locator('#auth-submit').click();
    await page.locator('#auth-dialog').waitFor({ state: 'hidden' });
    return { page, context };
  }
  const alice = await participant('Алиса', 'alice@example.com');
  await alice.page.waitForFunction(() => document.querySelector('#online-count').textContent === '1');
  assert.equal(await alice.page.locator('#map .leaflet-pane').count() > 0, true);
  assert.equal(await alice.page.locator('.map-bottom, .leaflet-attribution-flag').count(), 0);
  const attribution = await alice.page.locator('.leaflet-control-attribution').textContent();
  assert.match(attribution, /OpenStreetMap/);
  assert.match(attribution, /GeoNames/);
  assert.doesNotMatch(attribution, /Leaflet/);
  const bob = await participant('Боб', 'bob@example.com', true);
  for (const { page } of [alice, bob]) {
    await page.waitForFunction(() => document.querySelector('#online-count').textContent === '2');
    assert.equal(await page.locator('#map .leaflet-pane').count() > 0, true);
    assert.equal(await page.locator('.stat-card').count(), 2);
    assert.equal(await page.locator('#active-circles-count').textContent(), '0');
    assert.equal(await page.locator('.map-pin').count(), 0);
    assert.doesNotMatch(await page.locator('.online-card').textContent(), /Алиса|Боб|@/);
  }
  instance.applyPost({ id: 123, date: Date.now(), text: 'МО Раменское\nМосковская область\nОпасность по БПЛА' });
  await alice.page.waitForFunction(() => document.querySelector('#alerts-count').textContent.includes('1'));
  assert.equal(await alice.page.locator('#active-circles-count').textContent(), '1');
  await alice.page.waitForFunction(() => [...document.querySelectorAll('#map path.leaflet-interactive')].some(path => !path.getAttribute('d').includes('a')));
  await bob.page.waitForFunction(() => document.querySelector('#active-circles-count').textContent === '1');
  await bob.page.locator('.alert-toast').waitFor();
  const [mobileHeader, mobileToast] = await Promise.all([bob.page.locator('.map-heading').boundingBox(), bob.page.locator('.alert-toast').boundingBox()]);
  assert.ok(mobileToast.y > mobileHeader.y + mobileHeader.height);
  assert.equal(await alice.page.locator('#map path.leaflet-interactive').count(), 1);
  instance.applyPost({ id: 124, date: Date.now(), text: 'Московская область\nОтбой опасности по БПЛА' });
  await alice.page.waitForFunction(() => document.querySelector('#alerts-count').textContent.includes('0'));
  assert.equal(await alice.page.locator('#active-circles-count').textContent(), '0');
  await bob.page.waitForFunction(() => document.querySelector('#active-circles-count').textContent === '0');
  assert.equal(await alice.page.locator('#map path.leaflet-interactive').count(), 0);
  instance.applyPost({ source: 'radarrussiia', id: 125, date: Date.now(), text: 'Геленджик\nКраснодарский край\nОпасность по БПЛА' });
  await alice.page.waitForFunction(() => document.querySelector('#active-circles-count').textContent === '1');
  await alice.page.locator('#map path.leaflet-interactive').dispatchEvent('click');
  assert.equal(await alice.page.locator('.leaflet-popup-content a').getAttribute('href'), 'https://t.me/radarrussiia/125');
  instance.applyPost({ source: 'radarrussiia', id: 126, date: Date.now() + 1, text: 'Краснодарский край\nОтбой опасности по БПЛА' });
  await alice.page.waitForFunction(() => document.querySelector('#active-circles-count').textContent === '0');
  const [onlineCard, alertCard] = await Promise.all([bob.page.locator('.stat-card').first().boundingBox(), bob.page.locator('.stat-card').last().boundingBox()]);
  assert.equal(alertCard.x > onlineCard.x, true);
  assert.equal(await bob.page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  const secondTab = await alice.context.newPage(); await secondTab.goto(url);
  await secondTab.waitForFunction(() => document.querySelector('#online-count').textContent === '2');
  await secondTab.close();
  await bob.page.locator('#logout').click();
  await bob.page.locator('#auth-dialog').waitFor({ state: 'visible' });
  await alice.page.waitForFunction(() => document.querySelector('#online-count').textContent === '1');
  await bob.page.locator('#login-tab').click();
  await bob.page.locator('#email').fill('bob@example.com'); await bob.page.locator('#password').fill('correct horse battery'); await bob.page.locator('#auth-submit').click();
  await bob.page.locator('#auth-dialog').waitFor({ state: 'hidden' });
  await bob.page.waitForFunction(() => document.querySelector('#online-count').textContent === '2');
  await bob.page.reload();
  await bob.page.waitForFunction(() => document.querySelector('#online-count').textContent === '2');
  assert.equal(await bob.page.locator('#auth-dialog').isVisible(), false);
  assert.deepEqual(locationRequests, []);
  assert.deepEqual(errors, []);
});
