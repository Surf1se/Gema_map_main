test('Yandex tiles use Web Mercator and display the required logo', { timeout: 30_000 }, async t => {
  const instance = createApp({ database: ':memory:', secureCookies: false, yandexTilesKey: 'test-tiles-key' });
  const server = instance.app.listen(0, '127.0.0.1'); await once(server, 'listening');
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || (existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : undefined), args: ['--no-sandbox'] });
  t.after(async () => { await browser.close(); instance.close(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); });
  const page = await browser.newPage();
  const tileRequests = [];
  const logo = fileURLToPath(new URL('../public/yandex-logo.png', import.meta.url));
  await page.route('https://tiles.api-maps.yandex.ru/**', route => {
    tileRequests.push(new URL(route.request().url()));
    return route.fulfill({ path: logo, contentType: 'image/png' });
  });
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  await page.waitForFunction(() => document.querySelector('#yandex-logo')?.offsetParent !== null);
  await page.waitForFunction(() => [...document.querySelectorAll('.leaflet-tile')].some(tile => tile.complete && tile.naturalWidth));
  assert.ok(tileRequests.length > 0);
  assert.equal(tileRequests[0].searchParams.get('apikey'), 'test-tiles-key');
  assert.equal(tileRequests[0].searchParams.get('projection'), 'web_mercator');
  assert.equal(tileRequests[0].searchParams.get('lang'), 'ru_RU');
  assert.equal(await page.locator('#yandex-logo').getAttribute('href'), 'https://yandex.ru/maps/');
});

test('regions gray after an hour, cities stay red and show publication time until clearance', { timeout: 30_000 }, async t => {
  const polygon = { type: 'Polygon', coordinates: [[[37.1, 55.3], [38.5, 55.3], [38.5, 56], [37.1, 56], [37.1, 55.3]]] };
  const instance = createApp({ database: ':memory:', secureCookies: false, boundaryLookup: async () => polygon });
  instance.applyPost({ id: 301, date: Date.now(), text: 'Московская область\nОпасность по БПЛА' });
  const server = instance.app.listen(0, '127.0.0.1'); await once(server, 'listening');
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || (existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : undefined), args: ['--no-sandbox'] });
  t.after(async () => { await browser.close(); instance.close(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  await page.clock.install();
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  await page.locator('#name').fill('Карта'); await page.locator('#email').fill('map@example.com'); await page.locator('#password').fill('correct horse battery');
  await page.locator('#auth-submit').click();
  await page.locator('#auth-dialog').waitFor({ state: 'hidden' });
  const regionPath = page.locator('.leaflet-alert-region-pane path').first();
  await regionPath.waitFor();
  assert.equal(await regionPath.getAttribute('fill'), '#df3b3b');
  assert.equal(await regionPath.getAttribute('stroke'), '#59636b');
  assert.equal(await page.locator('.alert-toast').count(), 0);

  const cityPublishedAt = Date.now() - 10 * 60_000;
  instance.applyPost({ id: 302, date: Date.now(), publishedAt: cityPublishedAt, text: 'МО Раменское\nМосковская область\nОпасность по БПЛА' });
  const cityPath = page.locator('.leaflet-alert-settlement-pane path').first();
  await cityPath.waitFor();
  assert.equal(await cityPath.getAttribute('fill'), '#ed3030');
  assert.equal(await cityPath.getAttribute('stroke'), '#ffffff');
  assert.match(await cityPath.getAttribute('d'), /a/i);
  await cityPath.hover();
  const expectedTime = new Intl.DateTimeFormat('ru-RU', { timeZone: 'Europe/Moscow', day: '2-digit', month: '2-digit', year: 'numeric', hour: '2-digit', minute: '2-digit' }).format(new Date(cityPublishedAt));
  assert.match(await page.locator('.leaflet-tooltip').textContent(), new RegExp(`Опубликовано: ${expectedTime}`));
  await page.locator('.alert-toast').waitFor();
  assert.match(await page.locator('.alert-toast').textContent(), /Раменское/);
  const toastBox = await page.locator('.alert-toast').boundingBox();
  assert.ok(toastBox.x > 700 && toastBox.y < 170);
  await page.locator('.alert-toast button').click();
  assert.equal(await page.locator('.alert-toast').count(), 0);

  instance.applyPost({ id: 303, date: Date.now(), text: 'ГО Бронницы\nМосковская область\nРакетная опасность' });
  await page.locator('.alert-toast').waitFor();
  await page.clock.fastForward(120_001);
  assert.equal(await page.locator('.alert-toast').count(), 0);
  await page.clock.fastForward(58 * 60_000 + 5_000);
  await page.waitForFunction(() => [...document.querySelectorAll('.leaflet-alert-region-pane path')].every(path => path.getAttribute('fill') === '#9299a0'));
  assert.ok((await page.locator('.leaflet-alert-settlement-pane path').all()).every(Boolean));
  assert.equal(await cityPath.getAttribute('fill'), '#ed3030');
  await page.clock.fastForward(3 * 60 * 60_000 + 5_000);
  assert.ok((await page.locator('.leaflet-alert-settlement-pane path').all()).every(Boolean));
  assert.equal(await cityPath.getAttribute('fill'), '#ed3030');
  await page.clock.setSystemTime(new Date());
  instance.applyPost({ id: 302, date: Date.now(), publishedAt: cityPublishedAt, text: 'МО Раменское\nМосковская область\nОпасность по БПЛА' });
  await page.waitForFunction(() => [...document.querySelectorAll('.leaflet-alert-settlement-pane path')].some(path => path.getAttribute('fill') === '#ed3030'));
  await cityPath.hover();
  assert.match(await page.locator('.leaflet-tooltip').textContent(), new RegExp(`Опубликовано: ${expectedTime}`));
  assert.equal(await page.locator('.alert-toast').count(), 0);
  instance.applyPost({ id: 304, date: Date.now(), text: 'МО Раменское\nМосковская область\nОтбой' });
  await page.waitForFunction(() => [...document.querySelectorAll('.leaflet-alert-settlement-pane path')].some(path => path.getAttribute('fill') === '#2baa62'));
  await page.clock.fastForward(5 * 60_000 + 10);
  await page.waitForFunction(() => document.querySelectorAll('.leaflet-alert-settlement-pane path').length === 1);
  await page.waitForFunction(() => [...document.querySelectorAll('.leaflet-alert-settlement-pane path')].every(path => path.getAttribute('fill') !== '#2baa62'));
});

